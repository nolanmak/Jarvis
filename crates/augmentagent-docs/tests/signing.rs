/// Render one page to raw RGB at 72 dpi via poppler: (width, height, pixels).
fn render_page(pdf: &std::path::Path, page: u32) -> (usize, usize, Vec<u8>) {
    let dir = tempfile::tempdir().unwrap();
    let base = dir.path().join("page");
    let out = std::process::Command::new("pdftoppm")
        .args(["-r", "72", "-f", &page.to_string(), "-l", &page.to_string(), "-singlefile"])
        .arg(pdf)
        .arg(&base)
        .output()
        .expect("pdftoppm (poppler-utils) is required for the pixel checks");
    assert!(out.status.success(), "{}", String::from_utf8_lossy(&out.stderr));
    let ppm = std::fs::read(base.with_extension("ppm")).unwrap();
    // P6\n<w> <h>\n255\n<rgb>
    let mut fields = Vec::new();
    let mut i = 0;
    while fields.len() < 4 {
        while ppm[i].is_ascii_whitespace() { i += 1; }
        let start = i;
        while !ppm[i].is_ascii_whitespace() { i += 1; }
        fields.push(String::from_utf8(ppm[start..i].to_vec()).unwrap());
    }
    assert_eq!(fields[0], "P6");
    let (w, h) = (fields[1].parse().unwrap(), fields[2].parse().unwrap());
    (w, h, ppm[i + 1..].to_vec())
}

fn page_count(pdf: &std::path::Path) -> u32 {
    let out = std::process::Command::new("pdfinfo").arg(pdf).output().unwrap();
    String::from_utf8_lossy(&out.stdout)
        .lines()
        .find_map(|l| l.strip_prefix("Pages:").map(|n| n.trim().parse().unwrap()))
        .unwrap()
}

/// #1507 AC1–AC3 — the signed file is the original file, edited: the input
/// bytes are an exact prefix, every other page renders pixel-identical, and on
/// the signed page only pixels inside the signature box change.
#[tokio::test]
async fn signed_output_is_the_original_bytes_plus_the_signature_only() {
    let (_dir, root, state, original) = multi_page_fixture().await;
    signing::register_at(&state, &original).unwrap();
    let pages = page_count(&root.join("letter.pdf"));
    assert!(pages >= 2, "fixture must span pages, got {pages}");
    let request = PlacementRequest::ink(pages, 95., 300., 180., None);
    let p = signing::propose(&root, &state, "letter.pdf".as_ref(), "letter-signed.pdf".as_ref(), "default", request)
        .await
        .unwrap();
    let placement = p.placement.clone();
    signing::execute(&root, &state, &p).await.unwrap();
    let signed = std::fs::read(root.join("letter-signed.pdf")).unwrap();

    // AC1 — byte prefix.
    assert!(signed.len() > original.len());
    assert_eq!(&signed[..original.len()], &original[..], "original bytes must be preserved verbatim");

    // AC2 — unsigned pages identical.
    for page in 1..pages {
        assert!(
            render_page(&root.join("letter.pdf"), page) == render_page(&root.join("letter-signed.pdf"), page),
            "page {page} changed"
        );
    }

    // AC3 — signed page changes only inside the signature rectangle (+1px AA).
    let (w, h, before) = render_page(&root.join("letter.pdf"), pages);
    let (w2, h2, after) = render_page(&root.join("letter-signed.pdf"), pages);
    assert_eq!((w, h), (w2, h2));
    let png = image_height_ratio(include_bytes!("fixtures/signature-test.png"));
    let (x0, x1) = (placement.x - 1., placement.x + placement.width + 1.);
    let top = h as f64 - placement.y; // PDF y is from the bottom; pixels from the top
    let (y0, y1) = (top - placement.width * png - 1., top + 1.);
    let mut changed = 0;
    for y in 0..h {
        for x in 0..w {
            let i = (y * w + x) * 3;
            if before[i..i + 3] != after[i..i + 3] {
                changed += 1;
                let (fx, fy) = (x as f64, y as f64);
                assert!(fx >= x0 && fx <= x1 && fy >= y0 && fy <= y1, "pixel ({x},{y}) changed outside the signature box");
            }
        }
    }
    assert!(changed > 0, "the signature must be visible");
}

/// height/width of a PNG from its IHDR.
fn image_height_ratio(png: &[u8]) -> f64 {
    let w = u32::from_be_bytes(png[16..20].try_into().unwrap()) as f64;
    let h = u32::from_be_bytes(png[20..24].try_into().unwrap()) as f64;
    h / w
}

