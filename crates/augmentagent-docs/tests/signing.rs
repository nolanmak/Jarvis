/// Rewrite `pdf` through the PDF runtime with `edit` (Python on `w`, a pypdf
/// PdfWriter cloned from it) — builds real-world feature fixtures.
fn with_feature(pdf: &[u8], edit: &str) -> Vec<u8> {
    use std::io::Write;
    let python = std::env::var_os("AUGMENTAGENT_PDF_PYTHON").map(std::path::PathBuf::from).unwrap_or_else(|| {
        std::path::PathBuf::from(std::env::var_os("HOME").unwrap()).join(".local/share/augmentagent/pdf-runtime/bin/python3")
    });
    let script = format!(
        "import io,sys\nfrom pypdf import PdfReader, PdfWriter\nfrom pypdf.generic import *\n\
         w = PdfWriter(clone_from=PdfReader(io.BytesIO(sys.stdin.buffer.read())))\n{edit}\n\
         o = io.BytesIO(); w.write(o); sys.stdout.buffer.write(o.getvalue())\n"
    );
    let mut child = std::process::Command::new(python)
        .args(["-I", "-c", &script])
        .stdin(std::process::Stdio::piped())
        .stdout(std::process::Stdio::piped())
        .spawn()
        .unwrap();
    child.stdin.take().unwrap().write_all(pdf).unwrap();
    let out = child.wait_with_output().unwrap();
    assert!(out.status.success());
    out.stdout
}

