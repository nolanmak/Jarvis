use augmentagent_docs::{
    pdf,
    signing::{self, Placement},
};
fn place() -> Placement {
    Placement {
        page: 1,
        x: 72.,
        y: 72.,
        width: 144.,
        date: Some("2026-10-12".into()),
    }
}
#[tokio::test]
async fn signature_is_revision_bound_and_published_once() {
    let dir = tempfile::tempdir().unwrap();
    let root = dir.path().join("wiki");
    let state = dir.path().join("private");
    std::fs::create_dir(&root).unwrap();
    std::fs::write(
        root.join("contract.md"),
        "# Contract\n\nServices agreement.\n",
    )
    .unwrap();
    pdf::render_pdf(&root, std::path::Path::new("contract.md"), None)
        .await
        .unwrap();
    let original = std::fs::read(root.join("contract.pdf")).unwrap();
    signing::register_at(&state, &original).unwrap();
    let png = dir.path().join("test.png");
    std::fs::write(&png, include_bytes!("fixtures/signature-test.png")).unwrap();
    signing::install(&state, "default", &png).unwrap();
    assert!(signing::install(&state, "../escape", &png).is_err());
    let p = signing::propose(
        &root,
        &state,
        "contract.pdf".as_ref(),
        "signed.pdf".as_ref(),
        "default",
        place(),
    )
    .await
    .unwrap();
    assert!(!root.join("signed.pdf").exists());
    std::fs::write(root.join("contract.pdf"), b"changed").unwrap();
    assert!(signing::execute(&root, &state, &p)
        .await
        .unwrap_err()
        .to_string()
        .contains("changed"));
    std::fs::write(root.join("contract.pdf"), &original).unwrap();
    let asset = std::fs::read(state.join("default.png")).unwrap();
    std::fs::write(state.join("default.png"), b"changed").unwrap();
    assert!(signing::execute(&root, &state, &p).await.is_err());
    std::fs::write(state.join("default.png"), asset).unwrap();
    let receipt = signing::execute(&root, &state, &p).await.unwrap();
    signing::verify_receipt(&root, &receipt).unwrap();
    assert_eq!(std::fs::read(root.join("contract.pdf")).unwrap(), original);
    assert!(signing::execute(&root, &state, &p).await.is_err());
    assert!(signing::propose(
        &root,
        &state,
        "contract.pdf".as_ref(),
        "../escape.pdf".as_ref(),
        "default",
        place()
    )
    .await
    .is_err());
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        assert_eq!(
            std::fs::metadata(state.join("default.png"))
                .unwrap()
                .permissions()
                .mode()
                & 0o777,
            0o600
        );
    }
}

#[test]
fn concurrent_registration_of_identical_pdf_is_idempotent() {
    let dir = tempfile::tempdir().unwrap();
    let barrier = std::sync::Arc::new(std::sync::Barrier::new(32));
    let workers: Vec<_> = (0..32)
        .map(|_| {
            let state = dir.path().to_path_buf();
            let barrier = barrier.clone();
            std::thread::spawn(move || {
                barrier.wait();
                signing::register_at(&state, b"identical generated bytes")
            })
        })
        .collect();
    let results: Vec<_> = workers
        .into_iter()
        .map(|worker| worker.join().unwrap())
        .collect();
    for result in results {
        result.unwrap();
    }
    let marker = dir
        .path()
        .join("generated")
        .join(signing::digest(b"identical generated bytes"));
    assert_eq!(std::fs::read(&marker).unwrap(), b"generated-pdf-v1\n");
    std::fs::remove_file(&marker).unwrap();
    std::fs::create_dir(&marker).unwrap();
    assert!(signing::register_at(dir.path(), b"identical generated bytes").is_err());
}

/// #1507 — a multi-page rendered PDF in a fresh wiki, with the default
/// signature installed. Returns (tempdir, wiki root, private state, pdf bytes).
async fn multi_page_fixture() -> (tempfile::TempDir, std::path::PathBuf, std::path::PathBuf, Vec<u8>) {
    let dir = tempfile::tempdir().unwrap();
    let root = dir.path().join("wiki");
    let state = dir.path().join("private");
    std::fs::create_dir(&root).unwrap();
    let body: String = (1..=120).map(|i| format!("Paragraph {i} of the synthetic letter.\n\n")).collect();
    std::fs::write(root.join("letter.md"), format!("# Letter\n\n{body}")).unwrap();
    pdf::render_pdf(&root, std::path::Path::new("letter.md"), None).await.unwrap();
    let original = std::fs::read(root.join("letter.pdf")).unwrap();
    let png = dir.path().join("test.png");
    std::fs::write(&png, include_bytes!("fixtures/signature-test.png")).unwrap();
    signing::install(&state, "default", &png).unwrap();
    (dir, root, state, original)
}

/// Render one page to raw RGB at 72 dpi via poppler: (width, height, pixels).
fn render_page(pdf: &std::path::Path, page: u32) -> (usize, usize, Vec<u8>) {
    let dir = tempfile::tempdir().unwrap();
    let base = dir.path().join("page");
    let out = std::process::Command::new("pdftoppm")
        .args(["-r", "72", "-f", &page.to_string(), "-l", &page.to_string(), "-singlefile"])
        .arg(pdf)
        .arg(&base)
        .output()
        .expect("pdftoppm (poppler-utils) is required for the pixel checks");
    assert!(out.status.success(), "{}", String::from_utf8_lossy(&out.stderr));
    let ppm = std::fs::read(base.with_extension("ppm")).unwrap();
    // P6\n<w> <h>\n255\n<rgb>
    let mut fields = Vec::new();
    let mut i = 0;
    while fields.len() < 4 {
        while ppm[i].is_ascii_whitespace() { i += 1; }
        let start = i;
        while !ppm[i].is_ascii_whitespace() { i += 1; }
        fields.push(String::from_utf8(ppm[start..i].to_vec()).unwrap());
    }
    assert_eq!(fields[0], "P6");
    let (w, h) = (fields[1].parse().unwrap(), fields[2].parse().unwrap());
    (w, h, ppm[i + 1..].to_vec())
}

fn page_count(pdf: &std::path::Path) -> u32 {
    let out = std::process::Command::new("pdfinfo").arg(pdf).output().unwrap();
    String::from_utf8_lossy(&out.stdout)
        .lines()
        .find_map(|l| l.strip_prefix("Pages:").map(|n| n.trim().parse().unwrap()))
        .unwrap()
}

/// #1507 AC1–AC3 — the signed file is the original file, edited: the input
/// bytes are an exact prefix, every other page renders pixel-identical, and on
/// the signed page only pixels inside the signature box change.
#[tokio::test]
async fn signed_output_is_the_original_bytes_plus_the_signature_only() {
    let (_dir, root, state, original) = multi_page_fixture().await;
    signing::register_at(&state, &original).unwrap();
    let pages = page_count(&root.join("letter.pdf"));
    assert!(pages >= 2, "fixture must span pages, got {pages}");
    let placement = Placement { page: pages, x: 95., y: 300., width: 180., date: None };
    let p = signing::propose(&root, &state, "letter.pdf".as_ref(), "letter-signed.pdf".as_ref(), "default", placement.clone())
        .await
        .unwrap();
    signing::execute(&root, &state, &p).await.unwrap();
    let signed = std::fs::read(root.join("letter-signed.pdf")).unwrap();

    // AC1 — byte prefix.
    assert!(signed.len() > original.len());
    assert_eq!(&signed[..original.len()], &original[..], "original bytes must be preserved verbatim");

    // AC2 — unsigned pages identical.
    for page in 1..pages {
        assert!(
            render_page(&root.join("letter.pdf"), page) == render_page(&root.join("letter-signed.pdf"), page),
            "page {page} changed"
        );
    }

    // AC3 — signed page changes only inside the signature rectangle (+1px AA).
    let (w, h, before) = render_page(&root.join("letter.pdf"), pages);
    let (w2, h2, after) = render_page(&root.join("letter-signed.pdf"), pages);
    assert_eq!((w, h), (w2, h2));
    let png = image_height_ratio(include_bytes!("fixtures/signature-test.png"));
    let (x0, x1) = (placement.x - 1., placement.x + placement.width + 1.);
    let top = h as f64 - placement.y; // PDF y is from the bottom; pixels from the top
    let (y0, y1) = (top - placement.width * png - 1., top + 1.);
    let mut changed = 0;
    for y in 0..h {
        for x in 0..w {
            let i = (y * w + x) * 3;
            if before[i..i + 3] != after[i..i + 3] {
                changed += 1;
                let (fx, fy) = (x as f64, y as f64);
                assert!(fx >= x0 && fx <= x1 && fy >= y0 && fy <= y1, "pixel ({x},{y}) changed outside the signature box");
            }
        }
    }
    assert!(changed > 0, "the signature must be visible");
}

/// height/width of a PNG from its IHDR.
fn image_height_ratio(png: &[u8]) -> f64 {
    let w = u32::from_be_bytes(png[16..20].try_into().unwrap()) as f64;
    let h = u32::from_be_bytes(png[20..24].try_into().unwrap()) as f64;
    h / w
}

/// #1507 AC4/AC5 — an owner-uploaded PDF is staged byte-for-byte and becomes
/// signable; the same bytes merely written into the wiki are not.
#[tokio::test]
async fn owner_upload_is_staged_verbatim_and_only_then_signable() {
    let (_dir, root, state, original) = multi_page_fixture().await;
    std::fs::write(root.join("planted.pdf"), &original).unwrap();
    let refused = signing::propose(&root, &state, "planted.pdf".as_ref(), "planted-signed.pdf".as_ref(), "default",
        Placement { page: 1, x: 72., y: 72., width: 144., date: None }).await;
    assert!(refused.unwrap_err().to_string().contains("neither rendered by Jarvis nor uploaded by the owner"));

    assert!(signing::stage_owner_upload(&root, &state, "notes.pdf", b"not a pdf").is_err());
    let rel = signing::stage_owner_upload(&root, &state, "Upload Name.PDF", &original).unwrap();
    assert!(rel.is_relative() && rel.extension().unwrap() == "pdf", "{rel:?}");
    assert_eq!(std::fs::read(root.join(&rel)).unwrap(), original, "staged bytes must equal the upload");
    let out = rel.with_file_name("Upload Name-signed.pdf");
    let p = signing::propose(&root, &state, &rel, &out, "default",
        Placement { page: 1, x: 72., y: 72., width: 144., date: None }).await.unwrap();
    signing::execute(&root, &state, &p).await.unwrap();
    assert!(std::fs::read(root.join(&out)).unwrap().starts_with(&original));
}

/// Rewrite `pdf` through the PDF runtime with `edit` (Python on `w`, a pypdf
/// PdfWriter cloned from it) — builds real-world feature fixtures.
fn with_feature(pdf: &[u8], edit: &str) -> Vec<u8> {
    use std::io::Write;
    let python = std::env::var_os("AUGMENTAGENT_PDF_PYTHON").map(std::path::PathBuf::from).unwrap_or_else(|| {
        std::path::PathBuf::from(std::env::var_os("HOME").unwrap()).join(".local/share/augmentagent/pdf-runtime/bin/python3")
    });
    let script = format!(
        "import io,sys\nfrom pypdf import PdfReader, PdfWriter\nfrom pypdf.generic import *\n\
         w = PdfWriter(clone_from=PdfReader(io.BytesIO(sys.stdin.buffer.read())))\n{edit}\n\
         o = io.BytesIO(); w.write(o); sys.stdout.buffer.write(o.getvalue())\n"
    );
    let mut child = std::process::Command::new(python)
        .args(["-I", "-c", &script])
        .stdin(std::process::Stdio::piped())
        .stdout(std::process::Stdio::piped())
        .spawn()
        .unwrap();
    child.stdin.take().unwrap().write_all(pdf).unwrap();
    let out = child.wait_with_output().unwrap();
    assert!(out.status.success());
    out.stdout
}

/// #1507 AC6 — inert real-world features sign; executable/reflowing content
/// is refused before a card is ever posted.
#[tokio::test]
async fn benign_view_actions_and_forms_sign_but_scripts_launch_and_xfa_are_refused() {
    let (_dir, root, state, original) = multi_page_fixture().await;
    let fit_view = "w._root_object[NameObject('/OpenAction')] = ArrayObject([w.pages[0].indirect_reference, NameObject('/Fit')])";
    let plain_form = "w._root_object[NameObject('/AcroForm')] = DictionaryObject({NameObject('/Fields'): ArrayObject()})";
    let cases: &[(&str, String, bool)] = &[
        ("fit-view", fit_view.into(), true),
        ("plain-form", plain_form.into(), true),
        ("both", format!("{fit_view}\n{plain_form}"), true),
        ("doc-js", "w.add_js('app.alert(1)')".into(), false),
        ("open-js", "w._root_object[NameObject('/OpenAction')] = DictionaryObject({NameObject('/S'): NameObject('/JavaScript'), NameObject('/JS'): TextStringObject('x')})".into(), false),
        ("open-launch", "w._root_object[NameObject('/OpenAction')] = DictionaryObject({NameObject('/S'): NameObject('/Launch'), NameObject('/F'): TextStringObject('calc')})".into(), false),
        ("chained-js", "w._root_object[NameObject('/OpenAction')] = DictionaryObject({NameObject('/S'): NameObject('/GoTo'), NameObject('/D'): ArrayObject([w.pages[0].indirect_reference, NameObject('/Fit')]), NameObject('/Next'): DictionaryObject({NameObject('/S'): NameObject('/JavaScript'), NameObject('/JS'): TextStringObject('x')})})".into(), false),
        ("page-aa-js", "w.pages[0][NameObject('/AA')] = DictionaryObject({NameObject('/O'): DictionaryObject({NameObject('/S'): NameObject('/JavaScript'), NameObject('/JS'): TextStringObject('x')})})".into(), false),
        ("xfa", "w._root_object[NameObject('/AcroForm')] = DictionaryObject({NameObject('/Fields'): ArrayObject(), NameObject('/XFA'): TextStringObject('<xdp/>')})".into(), false),
    ];
    for (name, edit, signable) in cases {
        let bytes = with_feature(&original, edit);
        let rel = signing::stage_owner_upload(&root, &state, &format!("{name}.pdf"), &bytes).unwrap();
        let out = rel.with_file_name(format!("{name}-signed.pdf"));
        let proposed = signing::propose(&root, &state, &rel, &out, "default",
            Placement { page: 1, x: 72., y: 72., width: 144., date: None }).await;
        assert_eq!(proposed.is_ok(), *signable, "{name}: {proposed:?}");
        if let Ok(p) = proposed {
            signing::execute(&root, &state, &p).await.unwrap();
            assert!(std::fs::read(root.join(&out)).unwrap().starts_with(&bytes), "{name}: prefix");
        } else {
            assert!(format!("{:#}", proposed.unwrap_err()).contains("require manual signing"), "{name}");
        }
    }
}


/// #1507 review — producers that dedupe streams (Acrobat "Reduce size",
/// Ghostscript, templated letterheads) make pages share content objects.
/// Signing one page must not change how any other page renders: pypdf's
/// merge_page rewrote the shared stream in place, stamping the signature onto
/// every page that referenced it, or nulling a shared letterhead off them.
#[tokio::test]
async fn shared_content_streams_never_leak_the_signature_onto_other_pages() {
    let (_dir, root, state, original) = multi_page_fixture().await;
    let shared_stream = "w.pages[1][NameObject('/Contents')] = w.pages[0].raw_get('/Contents')";
    let shared_letterhead = "s = DecodedStreamObject()\ns.set_data(b'0 0 1 rg 20 20 100 10 re f')\nr = w._add_object(s)\n\
        for p in w.pages:\n    c = p.raw_get('/Contents')\n    p[NameObject('/Contents')] = ArrayObject([r, *(c.get_object() if isinstance(c.get_object(), list) else [c])])";
    for (name, edit) in [("shared-stream", shared_stream), ("shared-letterhead", shared_letterhead)] {
        let bytes = with_feature(&original, edit);
        let rel = signing::stage_owner_upload(&root, &state, &format!("{name}.pdf"), &bytes).unwrap();
        let out = rel.with_file_name(format!("{name}-signed.pdf"));
        let p = signing::propose(&root, &state, &rel, &out, "default",
            Placement { page: 1, x: 72., y: 72., width: 144., date: Some("2026-10-20".into()) }).await.unwrap();
        signing::execute(&root, &state, &p).await.unwrap();
        let signed = std::fs::read(root.join(&out)).unwrap();
        assert!(signed.starts_with(&bytes), "{name}: prefix");
        let pages = page_count(&root.join(&rel));
        for page in 2..=pages {
            assert!(render_page(&root.join(&rel), page) == render_page(&root.join(&out), page), "{name}: page {page} changed");
        }
        assert!(render_page(&root.join(&rel), 1) != render_page(&root.join(&out), 1), "{name}: signature missing");
    }
}

/// #1507 review — bookmarks can carry actions too.
